def ordinal(n):
    if n < 20: return ORD[n - 1]
    t, u = n // 10 * 10, n % 10
    if u == 0: return TENS[t] + "ая"
    return TENS_W[t] + " " + ORD[u - 1]
def pages(spec):
    out = []
    for part in spec.split(","):
        a, _, b = part.partition("-"); out += list(range(int(a), int(b or a) + 1))
    return out
